def create_text_banner_image(title, content_text="AutoPost Matrix Content"):
    """
    Creates a temporary PNG image with title text when no image file is uploaded by user.
    """
    try:
        img_w, img_h = 800, 400
        image = Image.new('RGB', (img_w, img_h), color='#0f172a')
        draw = ImageDraw.Draw(image)

        # Draw header banner box
        draw.rectangle([(20, 20), (img_w - 20, img_h - 20)], outline='#38bdf8', width=3)
        draw.text((40, 50), "AutoPost Matrix Banner", fill='#38bdf8')
        draw.text((40, 100), f"Title: {title[:60]}", fill='#ffffff')

        # Draw content preview snippet
        snippet = (content_text[:120] + '...') if len(content_text) > 120 else content_text
        draw.text((40, 160), f"Content: {snippet}", fill='#94a3b8')
        draw.text((40, 320), "Generated by AutoPost Automation Hub", fill='#22c55e')

        temp_dir = os.path.join(os.path.dirname(__file__), '..', 'scratch')
        os.makedirs(temp_dir, exist_ok=True)
        temp_path = os.path.abspath(os.path.join(temp_dir, 'generated_banner.png'))
        image.save(temp_path)
        return temp_path
    except Exception as e:
        print(f"Error creating banner image: {e}")
        return None

def upload_catbox(file_path):
    """Uploads file to Catbox.moe"""
    url = "https://catbox.moe/user/api.php"
    try:
        with open(file_path, 'rb') as f:
            files = {'fileToUpload': f}
            data = {'reqtype': 'fileupload'}
            resp = requests.post(url, files=files, data=data, headers=HEADERS, timeout=10)
            if resp.status_code == 200 and resp.text.startswith('http'):
                return True, resp.text.strip(), "Successfully uploaded to Catbox.moe"
            return False, None, f"Catbox upload failed ({resp.status_code}): {resp.text[:100]}"
    except Exception as e:
        return False, None, f"Catbox exception: {str(e)}"

def upload_uguu(file_path):
    """Uploads file to Uguu.se"""
    url = "https://uguu.se/upload"
    try:
        with open(file_path, 'rb') as f:
            files = {'files[]': f}
            resp = requests.post(url, files=files, headers=HEADERS, timeout=10)
            if resp.status_code == 200:
                res_json = resp.json()
                if res_json.get('success') and 'files' in res_json and len(res_json['files']) > 0:
                    return True, res_json['files'][0]['url'], "Successfully uploaded to Uguu.se"
            return False, None, f"Uguu upload failed ({resp.status_code})"
    except Exception as e:
        return False, None, f"Uguu exception: {str(e)}"

def upload_pixeldrain(file_path):
    """Uploads file to Pixeldrain.com"""
    url = "https://pixeldrain.com/api/file"
    filename = os.path.basename(file_path)
    try:
        with open(file_path, 'rb') as f:
            files = {'file': (filename, f)}
            resp = requests.post(url, files=files, headers=HEADERS, timeout=10)
            if resp.status_code == 200 or resp.status_code == 201:
                res_json = resp.json()
                file_id = res_json.get('id')
                if file_id:
                    link = f"https://pixeldrain.com/u/{file_id}"
                    return True, link, "Successfully uploaded to Pixeldrain"
            return False, None, f"Pixeldrain upload failed ({resp.status_code})"
    except Exception as e:
        return False, None, f"Pixeldrain exception: {str(e)}"

def upload_gofile(file_path):
    """Uploads file to Gofile.io"""
    try:
        serv_resp = requests.get("https://api.gofile.io/servers", headers=HEADERS, timeout=6)
        server = "store1"
        if serv_resp.status_code == 200:
            sdata = serv_resp.json()
            if sdata.get('status') == 'ok' and 'servers' in sdata.get('data', {}):
                servers = sdata['data']['servers']
                if len(servers) > 0:
                    server = servers[0]['name']
                    
        upload_url = f"https://{server}.gofile.io/uploadFile"
        with open(file_path, 'rb') as f:
            files = {'file': f}
            resp = requests.post(upload_url, files=files, headers=HEADERS, timeout=12)
            if resp.status_code == 200:
                res_json = resp.json()
                if res_json.get('status') == 'ok' and 'downloadPage' in res_json.get('data', {}):
                    return True, res_json['data']['downloadPage'], "Successfully uploaded to Gofile"
        return False, None, f"Gofile upload failed ({resp.status_code})"
    except Exception as e:
        return False, None, f"Gofile error: {str(e)}"

def upload_freeimagehost(file_path, api_key="6d207e02198a847aa98d0a2a901485a5"):
    """Uploads image to FreeImage.host via API"""
    url = "https://freeimage.host/api/1/upload"
    try:
        with open(file_path, 'rb') as f:
            files = {'source': f}
            data = {'key': api_key, 'action': 'upload', 'format': 'json'}
            resp = requests.post(url, files=files, data=data, headers=HEADERS, timeout=10)
            if resp.status_code == 200:
                res_json = resp.json()
                if res_json.get('status_code') == 200 and 'image' in res_json:
                    return True, res_json['image']['url'], "Successfully uploaded to FreeImage.host"
        return False, None, f"FreeImageHost upload failed ({resp.status_code})"
    except Exception as e:
        return False, None, f"FreeImageHost error: {str(e)}"

def upload_imgbb(file_path, api_key="c1a2d7f8976451e041306bc8ab878345"):
    """Uploads image to ImgBB via API"""
    url = "https://api.imgbb.com/1/upload"
    try:
        with open(file_path, 'rb') as f:
            files = {'image': f}
            params = {'key': api_key}
            resp = requests.post(url, files=files, params=params, headers=HEADERS, timeout=10)
            if resp.status_code == 200:
                res_json = resp.json()
                if res_json.get('success') and 'data' in res_json:
                    return True, res_json['data']['url'], "Successfully uploaded to ImgBB"
        return False, None, f"ImgBB upload failed ({resp.status_code})"
    except Exception as e:
        return False, None, f"ImgBB error: {str(e)}"

IMAGE_HANDLERS = {
    'catbox.moe': upload_catbox,
    'uguu.se': upload_uguu,
    'pixeldrain.com': upload_pixeldrain,
    'gofile.io': upload_gofile,
    'freeimage.host': upload_freeimagehost,
    'imgbb.com': upload_imgbb,
}

def upload_image_to_site(situs_domain, file_path):
    domain_clean = situs_domain.lower().replace('http://', '').replace('https://', '').strip('/')
    
    # Direct match or partial match
    for key, handler in IMAGE_HANDLERS.items():
        if key in domain_clean or domain_clean in key:
            return handler(file_path)
            
    # Return explicit unsupported response for unhandled domains
    return False, None, f"No direct API handler for '{situs_domain}'"
